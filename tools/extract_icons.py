#!/usr/bin/env python3
"""Regenerate src/icon_data.rs from the vendored official icon files.

The upstream assets are checked in under assets/icons/ so this conversion is
auditable and repeatable: nothing is drawn from memory, and re-running the
script after a `git pull` of a newer icon set is a one-liner.

    python tools/extract_icons.py

Sources and licences are listed in assets/icons/README.md.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "icons"
OUT = ROOT / "src" / "icon_data.rs"

# constant name -> (file, license note)
OCTICONS = {
    "GITHUB_INFO": "octicons/info-16.svg",
    "GITHUB_BULB": "octicons/light-bulb-16.svg",
    "GITHUB_REPORT": "octicons/report-16.svg",
    "GITHUB_ALERT": "octicons/alert-16.svg",
    "GITHUB_STOP": "octicons/stop-16.svg",
}
LUCIDE = {
    "OBSIDIAN_PENCIL": "lucide/lucide-pencil.svg",
    "OBSIDIAN_INFO": "lucide/lucide-info.svg",
    "OBSIDIAN_FLAME": "lucide/lucide-flame.svg",
    "OBSIDIAN_ALERT": "lucide/lucide-triangle-alert.svg",
    "OBSIDIAN_ZAP": "lucide/lucide-zap.svg",
    "OBSIDIAN_OCTAGON": "lucide/lucide-octagon-alert.svg",
    "OBSIDIAN_CHEVRON": "lucide/lucide-chevron-down.svg",
}
DOCUSAURUS = {
    "DOCUSAURUS_INFO": "docusaurus/docsaurus-Info.tsx",
    "DOCUSAURUS_TIP": "docusaurus/docsaurus-Tip.tsx",
    "DOCUSAURUS_NOTE": "docusaurus/docsaurus-Note.tsx",
    "DOCUSAURUS_DANGER": "docusaurus/docsaurus-Danger.tsx",
}


def read(rel: str) -> str:
    return (SRC / rel).read_text(encoding="utf-8")


def paths(text: str) -> list[tuple[str, bool]]:
    """Every <path d="..."> plus whether it asked for the even-odd rule."""
    out = []
    for tag in re.findall(r"<path\b[^>]*>", text, flags=re.S):
        d = re.search(r'd="([^"]+)"', tag, flags=re.S)
        if not d:
            continue
        even_odd = "evenodd" in tag
        # Whitespace inside a path string is not meaningful; collapse it so the
        # generated file stays readable.
        out.append((" ".join(d.group(1).split()), even_odd))
    return out


def circles(text: str) -> list[tuple[float, float, float]]:
    out = []
    for tag in re.findall(r"<circle\b[^>]*>", text):
        cx = float(re.search(r'cx="([^"]+)"', tag).group(1))
        cy = float(re.search(r'cy="([^"]+)"', tag).group(1))
        r = float(re.search(r'r="([^"]+)"', tag).group(1))
        out.append((cx, cy, r))
    return out


def emit(name: str, body: list[str]) -> str:
    lines = "\n".join(body)
    return f"pub const {name}: &[Shape] = &[\n{lines}\n];\n"


def main() -> None:
    body = []
    body.append(
        """//! Callout icon geometry, transcribed from the official icon sets.
//!
//! Generated by `tools/extract_icons.py` from the files under `assets/icons/`.
//! Do not edit by hand: re-run the script instead. The `d` attributes are
//! byte-for-byte what GitHub (octicons, MIT), Obsidian's icon set (lucide, ISC)
//! and Docusaurus (MIT) ship, so the icons match what those sites render.
"""
    )
    body.append("use crate::icon::{FillRule, Shape};\n")

    def block(consts: dict[str, str], stroked: bool, default_rule: str, note: str):
        body.append(f"// -- {note}")
        for name, rel in consts.items():
            text = read(rel)
            body.append(f"// {rel}")
            entries = []
            for cx, cy, r in circles(text):
                entries.append(
                    f"    Shape::Circle {{ c: [{cx}, {cy}], r: {r}, stroked: {str(stroked).lower()} }},"
                )
            for d, even_odd in paths(text):
                rule = "EvenOdd" if even_odd else default_rule
                entries.append(
                    "    Shape::Path { d: \"%s\", fill: FillRule::%s, stroked: %s },"
                    % (d, rule, str(stroked).lower())
                )
            body.append(emit(name, entries))

    block(OCTICONS, False, "NonZero", "GitHub alerts (octicons, filled)")
    block(LUCIDE, True, "NonZero", "Obsidian callouts (lucide, stroke only)")
    block(DOCUSAURUS, False, "EvenOdd", "Docusaurus admonitions (its own theme icons)")

    OUT.write_text("\n".join(body), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
